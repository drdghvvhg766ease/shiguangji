const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const base = 'http://localhost:5173', adminBase = 'http://localhost:5174'
const shots = path.resolve(__dirname, '../.shots')
async function json(response) { assert(response.ok(), await response.text()); return response.json() }
async function index(page, value) {
  await page.waitForTimeout(100)
  await page.waitForFunction(value => document.querySelector('.memory-position span')?.textContent.trim() === value, value)
}
async function main() {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 960 } })
  const errors = [], users = [], circles = []
  let page, admin
  try {
    users.push(await json(await context.request.post(base + '/api/auth/register', { data: { username: `memory_${Date.now()}`, nickname: '旅途收藏家', password: 'testpass1234' } })))
    const circle = await json(await context.request.post(base + '/api/circles', { data: { name: '四季生活影集' } }))
    circles.push(circle)
    const dates = ['2026-10-01', '2026-10-01', '2026-07-16', '2025-12-31', '2025-07-10', '2025-07-09']
    const posts = []
    for (let i = 0; i < dates.length; i++) {
      const video = i === dates.length - 1
      const file = video ? path.resolve(__dirname, 'fixtures/flower.mp4') : path.resolve(__dirname, '../frontend/user/public/preview-assets/' + ['friends.jpg', 'flowers.jpg', 'city.jpg'][i % 3])
      posts.push(await json(await context.request.post(`${base}/api/circles/${circle.id}/posts`, { multipart: { event_date: dates[i], content: `第 ${i + 1} 段四季回忆`, files: { name: path.basename(file), mimeType: video ? 'video/mp4' : 'image/jpeg', buffer: fs.readFileSync(file) } } })))
    }
    page = await context.newPage()
    page.on('pageerror', e => errors.push(e.message))
    page.on('console', m => { if (m.type() === 'warning' && m.text().includes('[Vue warn]')) errors.push(m.text()) })
    await page.goto(base)
    await page.locator('.featured-story .story-image').waitFor()
    // Both ports share one browser cookie jar, matching the reported regression.
    admin = await context.newPage()
    admin.on('pageerror', e => errors.push(e.message))
    await admin.goto(adminBase)
    await admin.locator('#login-layer button[type=submit]').click()
    await admin.locator('#login-layer.open').waitFor({ state: 'hidden' })
    assert.equal((await json(await context.request.get(base + '/api/auth/me'))).id, users[0].id)
    // Background tabs pause browser scroll animations and animation frames.
    await page.bringToFront()
    await page.getByRole('button', { name: '打开记录：第 3 段四季回忆', exact: true }).click()
    await page.locator('.record-original.ready').waitFor()
    await page.keyboard.press('Escape')
    await page.locator('.record-backdrop').waitFor({ state: 'hidden' })
    await page.locator('.side-nav').getByText('生活痕迹线', { exact: true }).click()
    await page.locator('.memory-navigator').waitFor()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await index(page, '1 / 6')
    assert.equal(await page.getByRole('button', { name: '上一刻', exact: true }).isDisabled(), true)
    await page.getByRole('button', { name: '下一刻', exact: true }).click()
    await index(page, '2 / 6')
    await page.getByRole('button', { name: '下一刻', exact: true }).press('ArrowRight')
    await index(page, '3 / 6')
    const before = await page.locator('.body-grid').evaluate(el => el.scrollTop)
    await page.getByRole('button', { name: '打开这一刻', exact: true }).click()
    await page.locator('.record-original.ready').waitFor()
    assert.equal((await page.locator('.record-content').textContent()).trim(), '第 3 段四季回忆')
    await page.keyboard.press('Escape')
    await page.locator('.record-backdrop').waitFor({ state: 'hidden' })
    assert(Math.abs(await page.locator('.body-grid').evaluate(el => el.scrollTop) - before) < 2)
    const oldId = await page.locator('.memory-strip [aria-current=true]').getAttribute('data-memory-id')
    await page.getByRole('button', { name: '随机回忆', exact: true }).click()
    await page.waitForTimeout(150)
    assert.notEqual(await page.locator('.memory-strip [aria-current=true]').getAttribute('data-memory-id'), oldId)
    await page.locator(`.memory-strip [data-memory-id="${posts[5].id}"]`).click()
    await index(page, '6 / 6')
    assert.equal(await page.getByRole('button', { name: '下一刻', exact: true }).isDisabled(), true)
    await page.getByRole('button', { name: '打开这一刻', exact: true }).click()
    await page.locator('.record-stage video').waitFor()
    await page.keyboard.press('Escape')
    await page.locator('.record-backdrop').waitFor({ state: 'hidden' })
    await page.locator('.body-grid').evaluate(el => el.scrollTop = 0)
    await page.getByLabel('选择年份', { exact: true }).selectOption('2025')
    await page.waitForTimeout(150)
    assert.equal(await page.locator('.memory-strip button').count(), 3)
    await page.getByLabel('选择年份', { exact: true }).selectOption('all')
    await page.waitForTimeout(150)
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: width === 390 ? 844 : 960 })
      await page.locator('.body-grid').evaluate(el => el.scrollTop = 0)
      await page.waitForTimeout(180)
      await page.getByRole('button', { name: '下一刻', exact: true }).click()
      await index(page, '2 / 6')
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      const navBox = await page.locator('.chronicle-navigation').boundingBox()
      const imageBox = await page.locator('.chronicle-story[data-current=true] .chronicle-images').boundingBox()
      assert(imageBox.y >= navBox.y + navBox.height, `sticky controls overlap image at ${width}`)
      await page.screenshot({ path: path.join(shots, `2026-10-01-memory-navigation-${width}.png`) })
      await page.getByRole('button', { name: '收起照片导航', exact: true }).click()
      await page.locator('.memory-strip').waitFor({ state: 'hidden' })
      await page.getByRole('button', { name: '展开照片导航', exact: true }).click()
    }
    await page.setViewportSize({ width: 1440, height: 960 })
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    await page.locator(`.memory-strip [data-memory-id="${posts[3].id}"]`).click()
    await page.waitForTimeout(1000)
    await index(page, '4 / 6')
    assert.equal(await page.locator('.chronicle-story[data-current=true]').evaluate(el => getComputedStyle(el).opacity), '1')
    assert((await page.locator('.month-nav button.active').textContent()).includes('2025 / 12'))
    await page.getByRole('button', { name: '上一刻', exact: true }).click()
    await page.waitForTimeout(1000)
    await index(page, '3 / 6')
    await page.locator('.compose-side').click()
    await page.getByRole('button', { name: '添加旅行地点', exact: true }).click()
    const search = page.getByRole('combobox', { name: '搜索城市或省份', exact: true })
    await search.fill('临沂')
    await page.locator('.city-results').getByRole('option').filter({ hasText: '临沂市' }).waitFor()
    await search.press('ArrowDown')
    await search.press('Enter')
    assert.equal(await page.getByLabel('地点名称', { exact: true }).inputValue(), '临沂市')
    assert(Number(await page.getByLabel('纬度', { exact: true }).inputValue()) > 34)
    await search.fill('广东')
    assert((await page.locator('.city-results').getByRole('option').count()) >= 20)
    await search.fill('不存在的城市xyz')
    await page.getByRole('status').filter({ hasText: '没有匹配城市' }).waitFor()
    for (const width of [1440, 768, 390]) {
      await page.setViewportSize({ width, height: width === 390 ? 844 : 960 })
      await search.fill('山东')
      await page.locator('.city-results').getByRole('option').first().waitFor()
      await page.waitForTimeout(180)
      const optionsBox = await page.locator('.city-search-popover').boundingBox()
      const topBarBox = await page.locator(width === 390 ? '.mobile-top' : '.topbar').boundingBox()
      const mobileNavBox = width === 390 ? await page.locator('.mobile-nav').boundingBox() : null
      assert(optionsBox.y >= topBarBox.y + topBarBox.height - 1, `city results clipped at top ${width}`)
      assert(optionsBox.y + optionsBox.height <= (mobileNavBox?.y || 960), `city results clipped at bottom ${width}`)
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
      await page.screenshot({ path: path.join(shots, `2026-10-01-city-search-${width}.png`) })
    }
    await search.press('Escape')
    await page.getByRole('button', { name: '清除地点', exact: true }).click()
    await page.setViewportSize({ width: 1440, height: 960 })
    await page.locator('.side-nav').getByText('照片墙', { exact: true }).click()
    await page.getByRole('button', { name: '打开记录：第 3 段四季回忆', exact: true }).click()
    await page.locator('.record-original.ready').waitFor()
    await page.getByRole('button', { name: '编辑记录', exact: true }).click()
    await page.locator('.record-edit').getByRole('combobox', { name: '搜索城市或省份', exact: true }).fill('临沂')
    await page.locator('.city-results').getByRole('option').first().waitFor()
    await page.keyboard.press('Escape')
    assert.equal(await page.locator('.record-dialog').isVisible(), true, 'Escape closes city options before dialog')
    await page.locator('.record-edit').getByRole('button', { name: '取消', exact: true }).click()
    await page.keyboard.press('Escape')
    await page.locator('.record-backdrop').waitFor({ state: 'hidden' })
    await admin.bringToFront()
    await admin.getByRole('button', { name: '退出', exact: true }).click()
    await page.bringToFront()
    await page.getByRole('button', { name: '打开记录：第 3 段四季回忆', exact: true }).click()
    await page.locator('.record-original.ready').waitFor()
    assert.deepEqual(errors, [])
    console.log('Memory/map checks passed: same-browser user/admin isolation, record access, city/province search, keyboard and Escape, year filtering, filmstrip, previous/next, random, video, detail return, sticky layout and 1440/768/390.')
  } catch (error) {
    if (page) console.log('Failure layout:', await page.evaluate(() => ({ scroll: document.querySelector('.body-grid')?.scrollTop, overflow: document.querySelector('.body-grid')?.style.overflow, current: document.querySelector('.memory-position')?.innerText, stories: [...document.querySelectorAll('[data-story]')].map(el => ({ id: el.dataset.story, top: el.getBoundingClientRect().top, visible: el.className })) })))
    if (page) await page.screenshot({ path: path.join(shots, 'memory-map-failure.png') })
    throw error
  } finally {
    for (const circle of circles) await context.request.delete(`${base}/api/circles/${circle.id}`)
    await json(await context.request.post(adminBase + '/api/admin/auth/login', { data: { username: 'admin', password: 'admin123' } }))
    for (const user of users) await json(await context.request.delete(adminBase + `/api/admin/users/${user.id}`, { data: { reason: '回忆导航与城市搜索验证账号清理' } }))
    await browser.close()
  }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
